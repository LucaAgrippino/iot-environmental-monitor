/**
 * @file panic_symbols.h
 * @brief On-device fault-address symbol resolution (Track B, panic decoder).
 *
 * The table itself (g_panic_symbols/g_panic_symbol_count/g_panic_files) is
 * generated at build time by scripts/gen-panic-symbols.py from
 * the image map (gateway.map or field_device_app.map) — see
 * panic_symbols_data.c (gitignored, not this file). panic_symbol_lookup()
 * is hand-written and generic over any sorted table, specifically so it
 * stays unit-testable against a small fixture without needing the real,
 * ~658-entry generated one.
 */

#ifndef PANIC_SYMBOLS_H
#define PANIC_SYMBOLS_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/** @brief One entry of the symbol table used to name the program counter in a panic report. */
typedef struct
{
    uint32_t addr;      /**< Address of the symbol. */
    uint32_t size;      /**< Size of the symbol in bytes. */
    const char *name;   /**< Name of the symbol. */
    uint8_t file_index; /**< Index into a caller-supplied file-name table. */
} panic_symbol_t;

/** Defined in panic_symbols_data.c (gitignored, generated by
 * scripts/gen-panic-symbols.py), with empty weak fallbacks in
 * panic_symbols.c so a fresh checkout still links — declared here so
 * cpu.c can reference them; not needed by panic_symbol_lookup() itself,
 * which takes any table as a parameter instead (see its own doc comment
 * below). */
extern const panic_symbol_t g_panic_symbols[];
/** @brief Number of entries in g_panic_symbols. */
extern const uint32_t g_panic_symbol_count;
/** @brief File names that file_index refers to. */
extern const char *const g_panic_files[];

/** Address of cpu_panic() in the image the table was generated from (0 if there is no table). The
 * table is only used when this equals the running cpu_panic(): a table from an earlier build has
 * shifted addresses and would print wrong function names (cpu-driver.md CPU-O5). */
extern const uint32_t g_panic_anchor_addr;

/** End of the code (_etext) of the image the table was generated from. Any change in code size
 * moves it, so it catches a table that is stale for functions after cpu_panic() as well. */
extern const uint32_t g_panic_text_end;

/**
 * @brief Decide whether the generated table belongs to the running image.
 *
 * @param[in] anchor         g_panic_anchor_addr.
 * @param[in] cpu_panic_addr Address of cpu_panic() in the running image (Thumb bit allowed).
 * @param[in] text_end       g_panic_text_end.
 * @param[in] etext_addr     Address of _etext in the running image.
 * @param[in] count          g_panic_symbol_count.
 * @return true when the table is non-empty and was generated from this image.
 */
bool panic_symbols_match(uint32_t anchor, uint32_t cpu_panic_addr, uint32_t text_end,
                         uint32_t etext_addr, uint32_t count);

/**
 * @brief Find the function symbol containing addr, if any.
 *
 * Binary search — table must be sorted by addr ascending (the generator
 * guarantees this; a hand-built test fixture must too). Deliberately
 * tolerant of addr values outside every known range (including addresses
 * that don't correspond to real code at all, e.g. a corrupted/garbage
 * pointer) — this runs inside a fault handler, where a lookup that itself
 * misbehaves on unexpected input is worse than one that just returns NULL.
 *
 * @param[in] table  Sorted-by-addr symbol table (may be the real generated
 *                    one, or a small test fixture).
 * @param[in] count  Number of entries in table.
 * @param[in] addr   Address to resolve (e.g. a faulting PC or LR).
 * @return Pointer into table for the containing symbol (addr falls within
 *         [entry->addr, entry->addr + entry->size)), or NULL if none
 *         contains it (including table == NULL or count == 0).
 */
const panic_symbol_t *panic_symbol_lookup(const panic_symbol_t *table, uint32_t count,
                                          uint32_t addr);

#endif /* PANIC_SYMBOLS_H */
