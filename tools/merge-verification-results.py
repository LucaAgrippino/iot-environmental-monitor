#!/usr/bin/env python3
"""Merge Robot Framework results into docs/test/verification-results.md.

Reads the output.xml of one or more runs (default: every run under verification/build/results/, oldest first).
For each test case (TC-VER-...) the LATEST run that executed it wins, so a re-run replaces an earlier failure.
Each test names the requirements it verifies with REQ-XX-NNN tags; a requirement is then

  Verified    every test tagged with it passed in its latest run
  Failed      at least one such test failed in its latest run
  Not run     no test tagged with it has been executed

A requirement checked by hand (inspection, a bench measurement, an operator step) is recorded in
docs/test/manual-results.csv (requirement, verdict PASS or FAIL, date, who, evidence); it then counts as
"Verified (manual)" or "Failed". A failing Robot test still wins over a manual PASS.

The requirement list and the method of each come from docs/test/verification-methods.csv.
Run from anywhere:  tools/merge-verification-results.py [run-dir-or-output.xml ...] [--check]
--check exits 1 when any executed test failed (for CI or a release gate); it does not rewrite the report.
"""
import csv
import re
import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "verification/build/results"
METHODS = ROOT / "docs/test/verification-methods.csv"
OUT = ROOT / "docs/test/verification-results.md"
MANUAL = ROOT / "docs/test/manual-results.csv"
REQ = re.compile(r"^REQ-[A-Z]{2}-\d{3}$")
TC = re.compile(r"^TC-[A-Z]+(?:-[A-Z0-9]+)*-\d+[a-z]?")


def find_outputs(args):
    if not args:
        return sorted(RESULTS.glob("*/output.xml"))
    found = []
    for a in args:
        p = Path(a)
        found += sorted(p.glob("*/output.xml")) if p.is_dir() and not (p / "output.xml").exists() else [p / "output.xml" if p.is_dir() else p]
    return found


def load_tests(outputs):
    """Latest result per test-case id. A later file overrides an earlier one."""
    latest = {}
    for out in outputs:
        if not out.exists():
            continue
        root = ET.parse(out).getroot()
        run = out.parent.name
        for t in root.iter("test"):
            st = t.find("status")
            m = TC.match(t.get("name", ""))
            if st is None or m is None or st.get("status") == "SKIP":
                continue
            tags = [x.text for x in t.findall("./tag") if x.text]
            latest[m.group(0)] = {
                "name": t.get("name"),
                "status": st.get("status"),
                "run": run,
                "reqs": sorted(x for x in tags if REQ.match(x)),
                "unit": "unit-credit" in tags,
                "message": (st.text or "").strip().splitlines()[0][:160] if st.text else "",
            }
    return latest


def main():
    argv = sys.argv[1:]
    check = "--check" in argv
    outputs = find_outputs([a for a in argv if a != "--check"])
    tests = load_tests(outputs)
    if not tests:
        sys.exit("no Robot results found (run verification/run.sh first)")

    reqs = list(csv.DictReader(METHODS.open(newline="")))
    by_req = defaultdict(list)
    for tc, t in tests.items():
        for r in t["reqs"]:
            by_req[r].append(tc)
    known = {r["id"] for r in reqs}
    unknown = sorted(set(by_req) - known)

    manual = {}
    if MANUAL.exists():
        for row in csv.DictReader(MANUAL.open(newline="")):
            manual[row["requirement"]] = row

    def status(rid):
        tcs = by_req.get(rid, [])
        if not tcs:
            m = manual.get(rid)
            if m:
                return "Verified (manual)" if m["verdict"].upper() == "PASS" else "Failed"
            return "Not run"
        return "Failed" if any(tests[x]["status"] != "PASS" for x in tcs) else "Verified"

    count = Counter(status(r["id"]) for r in reqs)
    passed = sum(t["status"] == "PASS" for t in tests.values())
    failed = [tc for tc, t in sorted(tests.items()) if t["status"] != "PASS"]
    runs = sorted({t["run"] for t in tests.values()})

    if check:
        print(f"{passed}/{len(tests)} tests pass; failed: {', '.join(failed) or 'none'}")
        sys.exit(1 if failed else 0)

    n = len(reqs)
    L = [
        "# Verification results",
        "",
        "**Generated by `tools/merge-verification-results.py` from the Robot Framework runs. Do not edit by hand.**",
        "",
        f"Runs merged: {len(runs)} ({runs[0]} to {runs[-1]}). For each test the latest run that executed it counts.",
        "Method and level of every requirement: `verification-method-table.md`. Plan: `verification-plan.md`.",
        "",
        "## Summary",
        "",
        "| | Count |",
        "|---|---|",
        f"| Test cases executed | {len(tests)} |",
        f"| Test cases passing | {passed} |",
        f"| Test cases failing | {len(failed)} |",
        f"| Requirements | {n} |",
        f"| Verified (all tagged tests pass) | {count['Verified']} |",
        f"| Verified by hand (docs/test/manual-results.csv) | {count['Verified (manual)']} |",
        f"| Failed | {count['Failed']} |",
        f"| Not run yet | {count['Not run']} |",
        "",
    ]
    if unknown:
        L += [f"Tags naming requirements that are not in the method table: {', '.join(unknown)}.", ""]

    L += ["## Test cases", "", "| Test case | Result | Run | Requirements |", "|---|---|---|---|"]
    for tc, t in sorted(tests.items()):
        mark = "PASS" if t["status"] == "PASS" else f"**{t['status']}**"
        reqs_txt = ", ".join(t["reqs"]) if t["reqs"] else ("unit-credit" if t["unit"] else "-")
        L.append(f"| {tc} | {mark} | {t['run']} | {reqs_txt} |")
    L.append("")

    L += ["## Requirements", "", "| Requirement | Method | Board | Status | Test cases |", "|---|---|---|---|---|"]
    for r in reqs:
        s = status(r["id"])
        s_txt = s if s != "Failed" else "**Failed**"
        who = ", ".join(sorted(by_req.get(r["id"], []))) or (f"manual {manual[r['id']]['date']}" if r["id"] in manual else "-")
        L.append(f"| {r['id']} | {r['method']} | {r['board']} | {s_txt} | {who} |")
    L.append("")

    if failed:
        L += ["## Failing test cases", ""]
        L += [f"- {tc}: {tests[tc]['message']}" for tc in failed]
        L.append("")

    OUT.write_text("\n".join(L))
    print(f"wrote {OUT.relative_to(ROOT)}: {passed}/{len(tests)} tests pass; "
          f"requirements verified {count['Verified']}, failed {count['Failed']}, not run {count['Not run']}")


if __name__ == "__main__":
    main()
