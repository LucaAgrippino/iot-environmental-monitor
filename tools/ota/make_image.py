#!/usr/bin/env python3
"""Build and sign OTA firmware images for the Gateway FirmwareStore.

Format: docs/lld/middleware/firmware-store.md section 6.1 and
firmware/gateway/middleware/firmware_store/firmware_image_format.h.

  file   = header (128 B) || body
  header = magic, header_version, header_size, image_len, version, load_addr,
           reserved[12], body_sha256[32], signature[64]
  signature = ECDSA-P256 raw r||s (big-endian, 32 + 32) over SHA-256 of header
              bytes 0x00..0x3F

Each release produces TWO images, one linked for Slot A and one for Slot B,
because the slots are execute-in-place and not position-independent.

Commands
  genkey   create a release key pair; writes ota_public_key.c
  sign     wrap a linked body in a signed header
  vectors  regenerate the TEST-ONLY vectors used by the host unit tests

Requires the Python 'cryptography' package.
"""

import argparse
import hashlib
import struct
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import (
    decode_dss_signature,
)

MAGIC = 0x4F544131
HEADER_VERSION = 1
HEADER_SIZE = 128
SIGNED_LEN = 0x40
MAX_IMAGE_LEN = 491520
SLOT_BASE = {"A": 0x08006000, "B": 0x08080000}

REPO = Path(__file__).resolve().parents[2]
PUBLIC_KEY_C = (
    REPO / "firmware/gateway/middleware/firmware_store/ota_public_key.c"
)
VECTOR_DIR = REPO / "tests/gateway/middleware/firmware_store/vectors"


def raw_public_key(key):
    """Return the 64-byte X||Y of a P-256 public key."""
    numbers = key.public_key().public_numbers()
    return numbers.x.to_bytes(32, "big") + numbers.y.to_bytes(32, "big")


def parse_version(text):
    major, minor, patch = (int(p) for p in text.split("."))
    if not (0 <= major < 256 and 0 <= minor < 256 and 0 <= patch < 65536):
        raise ValueError("version out of range: " + text)
    return (major << 24) | (minor << 16) | patch


def check_link_base(body, load_addr):
    """The reset vector must carry the Thumb bit and point inside the image."""
    if len(body) < 8 or len(body) > MAX_IMAGE_LEN:
        raise ValueError("body length %d out of range" % len(body))
    reset = struct.unpack_from("<I", body, 4)[0]
    target = reset & ~1
    if not reset & 1 or not load_addr <= target < load_addr + len(body):
        raise ValueError(
            "reset vector 0x%08X is not inside the image linked at 0x%08X "
            "(wrong slot, or not a Thumb vector table?)" % (reset, load_addr)
        )


def build_image(body, slot, version, key):
    """Return header||body for the given slot, signed with key."""
    load_addr = SLOT_BASE[slot]
    check_link_base(body, load_addr)
    head = struct.pack(
        "<IHHIII12x32s",
        MAGIC,
        HEADER_VERSION,
        HEADER_SIZE,
        len(body),
        version,
        load_addr,
        hashlib.sha256(body).digest(),
    )
    assert len(head) == SIGNED_LEN
    der = key.sign(head, ec.ECDSA(hashes.SHA256()))
    r, s = decode_dss_signature(der)
    signature = r.to_bytes(32, "big") + s.to_bytes(32, "big")
    return head + signature + body


def write_public_key_c(key, path):
    pub = raw_public_key(key)
    rows = []
    for i in range(0, 64, 8):
        rows.append("    " + ", ".join("0x%02X" % b for b in pub[i:i + 8]) + ",")
    text = (
        "/**\n"
        " * @file ota_public_key.c\n"
        " * @brief Release public key for OTA image verification (raw P-256, X || Y).\n"
        " *\n"
        " * GENERATED by tools/ota/make_image.py genkey. Do not edit by hand.\n"
        " * The matching private key never enters git (tools/ota/README.md).\n"
        " */\n\n"
        '#include "ota_crypto.h"\n\n'
        "const uint8_t ota_public_key[OTA_PUBLIC_KEY_LEN] = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )
    Path(path).write_text(text)


def cmd_genkey(args):
    private = Path(args.private)
    if private.exists():
        sys.exit("refusing to overwrite " + str(private))
    key = ec.generate_private_key(ec.SECP256R1())
    private.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    private.chmod(0o600)
    write_public_key_c(key, args.public_c)
    print("private key:", private, "(keep it OUT of git)")
    print("public key :", args.public_c)


def cmd_sign(args):
    key = serialization.load_pem_private_key(
        Path(args.private).read_bytes(), password=None
    )
    body = Path(args.body).read_bytes()
    image = build_image(body, args.slot, parse_version(args.version), key)
    Path(args.out).write_bytes(image)
    print("wrote %s (%d bytes, Slot %s)" % (args.out, len(image), args.slot))


def pseudo_body(length, load_addr, seed):
    """Deterministic body with a valid-looking vector table."""
    out = bytearray()
    counter = 0
    while len(out) < length:
        out += hashlib.sha256(b"%d:%d" % (seed, counter)).digest()
        counter += 1
    body = bytearray(out[:length])
    struct.pack_into("<II", body, 0, 0x20018000, load_addr + 0x101)
    return bytes(body)


def c_array(name, data):
    rows = []
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        rows.append("    " + ", ".join("0x%02X" % b for b in chunk) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (
        name, len(data), "\n".join(rows)
    )


def load_or_create(path):
    if path.exists():
        return serialization.load_pem_private_key(
            path.read_bytes(), password=None
        )
    key = ec.generate_private_key(ec.SECP256R1())
    path.write_bytes(
        key.private_bytes(
            serialization.Encoding.PEM,
            serialization.PrivateFormat.PKCS8,
            serialization.NoEncryption(),
        )
    )
    return key


def cmd_vectors(_args):
    """TEST ONLY: regenerate keys and signed images for test_fs_crypto_vectors.c."""
    VECTOR_DIR.mkdir(parents=True, exist_ok=True)
    signer = load_or_create(VECTOR_DIR / "test_key_signer.pem")
    other = load_or_create(VECTOR_DIR / "test_key_other.pem")
    version = parse_version("2.3.4")
    body_len = 4200  # three pages: 2048 + 2048 + 104, so the last is padded
    body_b = pseudo_body(body_len, SLOT_BASE["B"], 11)
    body_a = pseudo_body(body_len, SLOT_BASE["A"], 11)
    parts = [
        "/**\n * @file test_vectors.h\n"
        " * @brief GENERATED TEST-ONLY signed images for test_fs_crypto_vectors.c.\n"
        " *\n * Regenerate with: tools/ota/make_image.py vectors\n"
        " * The keys are throw-away test keys committed beside this file; they sign\n"
        " * nothing but these vectors.\n */\n\n"
        "#ifndef TEST_VECTORS_H\n#define TEST_VECTORS_H\n\n#include <stdint.h>\n\n",
        "#define TV_BODY_LEN (%du)\n" % body_len,
        "#define TV_VERSION (0x%08Xu)\n\n" % version,
        "/* Raw X||Y of the key that signed the valid images, as an initialiser list. */\n",
        "#define TV_PUBLIC_KEY_BYTES \\\n    "
        + ", \\\n    ".join(
            ", ".join("0x%02X" % b for b in raw_public_key(signer)[i:i + 8])
            for i in range(0, 64, 8)
        )
        + "\n",
        "\n/* Linked for Slot B, signed by the test key. */\n",
        c_array("tv_image_slot_b", build_image(body_b, "B", version, signer)),
        "\n/* Same body linked for Slot A. */\n",
        c_array("tv_image_slot_a", build_image(body_a, "A", version, signer)),
        "\n/* Linked for Slot B, signed by a different key. */\n",
        c_array("tv_image_other_key", build_image(body_b, "B", version, other)),
        "\n#endif /* TEST_VECTORS_H */\n",
    ]
    (VECTOR_DIR / "test_vectors.h").write_text("".join(parts))
    print("wrote", VECTOR_DIR / "test_vectors.h")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)

    gen = sub.add_parser("genkey", help="create a release key pair")
    gen.add_argument("--private", required=True, help="PEM path OUTSIDE the repo")
    gen.add_argument("--public-c", default=str(PUBLIC_KEY_C))
    gen.set_defaults(func=cmd_genkey)

    sign = sub.add_parser("sign", help="sign a linked body")
    sign.add_argument("--body", required=True)
    sign.add_argument("--slot", choices=("A", "B"), required=True)
    sign.add_argument("--version", required=True, help="major.minor.patch")
    sign.add_argument("--private", required=True)
    sign.add_argument("--out", required=True)
    sign.set_defaults(func=cmd_sign)

    vec = sub.add_parser("vectors", help="regenerate the TEST-ONLY unit-test vectors")
    vec.set_defaults(func=cmd_vectors)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
