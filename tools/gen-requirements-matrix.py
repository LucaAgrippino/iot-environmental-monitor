#!/usr/bin/env python3
"""Generate docs/test/requirements-traceability.md from the SRS.

For every REQ-XX-NNN in docs/SRS.md, record where it is cited: HLD documents,
LLD companions (with any TC-... test-case IDs on the same line), and firmware
or test source. Pure text search - a requirement that is implemented but never
named in a comment shows as "No reference". Run from the repository root.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ = re.compile(r'REQ-[A-Z]{2}-\d{3}')
TC = re.compile(r'\bTC-[A-Z]+(?:-[A-Z0-9]+)*-\d+[a-z]?\b')

srs = (ROOT / 'docs/SRS.md').read_text()
body, matrix = srs.split('## 6. Traceability')
text = {}
for m in re.finditer(r'^- \[(REQ-[A-Z]+-\d+)\]\s*(.*)', body, re.M):
    text[m.group(1)] = m.group(2).strip()
uc = {}
for m in re.finditer(r'^\| (REQ-[A-Z]+-\d+) \| ([^|]*)\|', matrix, re.M):
    uc[m.group(1)] = m.group(2).strip()
sec = {}
cur = ''
for line in body.split('\n'):
    h = re.match(r'### (\d\.\d [^\n]*?)(?: — \d+ requirements)?$', line)
    if h: cur = h.group(1)
    r = re.match(r'- \[(REQ-[A-Z]+-\d+)\]', line)
    if r: sec[r.group(1)] = cur

def scan(paths, exts):
    hits = {r: set() for r in text}; tcs = {r: set() for r in text}
    for base in paths:
        for f in sorted((ROOT / base).rglob('*')):
            if not f.is_file() or f.suffix not in exts or 'build' in f.parts: continue
            try: lines = f.read_text(errors='ignore').split('\n')
            except OSError: continue
            rel = str(f.relative_to(ROOT))
            for ln in lines:
                for r in set(REQ.findall(ln)):
                    # "REQ-SA-090" also matches inside ranges; exact IDs only
                    if r in hits:
                        hits[r].add(rel); tcs[r].update(TC.findall(ln))
    return hits, tcs

hld, _ = scan(['docs/hld'], {'.md'})
for r in hld:  # gate-review audits describe SRS defects, not design
    hld[r] = {p for p in hld[r] if 'gate-review' not in p}
lld, lldtc = scan(['docs/lld'], {'.md'})
for r in lld:
    lld[r] = {p for p in lld[r] if 'gate-review' not in p}
code, codetc = scan(['firmware', 'tests'], {'.c', '.h', '.py'})

def label(r):
    d = bool(lld[r]); h = bool(hld[r]); c = bool(code[r])
    if c and d: return 'LLD + code'
    if d: return 'LLD'
    if c: return 'code'
    if h: return 'HLD only'
    return 'No reference'

rows = []
for r in text:
    short = lambda s: ', '.join(sorted(Path(p).stem for p in s)) or '-'
    tcl = sorted(lldtc[r] | codetc[r])
    tcs = ', '.join(tcl[:6]) + (f' (+{len(tcl)-6})' if len(tcl) > 6 else '') if tcl else '-'
    rows.append((r, sec[r], uc.get(r, ''), label(r), short(hld[r]), short(lld[r]), tcs))

from collections import Counter
cnt = Counter(x[3] for x in rows)
out = ['# Requirements traceability matrix', '',
       '**Generated by `tools/gen-requirements-matrix.py` from `docs/SRS.md` - do not edit by hand.**', '',
       f'SRS requirements: **{len(rows)}**. Regenerate with `python3 -I tools/gen-requirements-matrix.py`.', '',
       '## How to read this', '',
       'The evidence is a text search for the requirement ID (HLD documents excluding gate-review audits, LLD companions excluding gate-review, firmware and test sources). '
       '"Test cases" lists TC-... IDs that appear on the same line as the requirement ID; it does not prove a test passed - the LLD result tables do. '
       '**"No reference" means no document or source names the ID, not that the feature is missing**: a requirement can be implemented and simply never cited. '
       'Each such row needs a human decision: add the citation, or record the gap.', '',
       '| Evidence | Count |', '|---|---|']
for k in ['LLD + code', 'LLD', 'code', 'HLD only', 'No reference']:
    out.append(f'| {k} | {cnt.get(k, 0)} |')
out += ['', '## Requirements with no reference', '',
        '| ID | Section | Requirement |', '|---|---|---|']
for r, s_, u, l, *_ in rows:
    if l == 'No reference':
        out.append(f'| {r} | {s_} | {text[r][:110].replace("|", "/")} |')
out += ['', '## Requirements cited in the HLD only', '',
        '| ID | Section | HLD document |', '|---|---|---|']
for r, s_, u, l, h, *_ in rows:
    if l == 'HLD only': out.append(f'| {r} | {s_} | {h} |')
out += ['', '## Full matrix', '',
        '| ID | Use cases | Evidence | HLD | LLD | Test cases |', '|---|---|---|---|---|---|']
for r, s_, u, l, h, d, t in rows:
    out.append(f'| {r} | {u} | {l} | {h} | {d} | {t} |')
dest = ROOT / 'docs/test/requirements-traceability.md'
dest.write_text('\n'.join(out) + '\n')
print(len(rows), dict(cnt))
