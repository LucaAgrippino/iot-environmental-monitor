/**
 * @file main_spike_wifi_tls.c
 * @brief SPIKE (branch spike/wifi-module-tls, never merged): can the ISM43362's own TLS talk to our
 *        broker, and to AWS IoT Core?
 *
 * Question: the gateway runs mbedTLS on the host (44 KB static arena). The module has its own TLS
 * (AT P1=3, certificates by PG/PF, verification by P9). If it works with our certificates and
 * broker, most of that arena is not needed. This image answers it on the bench; it is not product code.
 *
 * What it does (all through wifi_spike_raw_at(), every reply logged with CR/LF visible):
 *   S0  I? and PE            module firmware and which certificate sets exist
 *   S1  PF, PG x3, PE        load CA, client certificate and key (skipped if SPIKE_LOAD_CERTS=0)
 *   S2  P9, P0, P1=3, P3/D0, P4   configure a TCP-SSL socket
 *   S3  P6=1                 connect + TLS handshake (the experiment; timed)
 *   S4  MQTT CONNECT, R0     expect CONNACK 20 02 00 00 if application data flows
 *   S5  MQTT PUBLISH QoS 0   topic spike/wifi-tls
 *   S6  P6=0                 close
 *
 * Build and run: see README.md in this directory (build.sh, no .cproject change).
 * Uses USART1 PB6 115 200 8N1 like the other bring-up mains; LD2 blinks when finished.
 */

