static char s_resp[2048];
static uint8_t s_cmd[2048];

/** Log @p n bytes of module text with CR/LF/non-printables made visible, in short lines. */
static void spike_log_text(const char *tag, const char *s, size_t n)
{
    char line[88];
    size_t o = 0U;

    for (size_t i = 0U; i < n; i++)
    {
        const unsigned char c = (unsigned char) s[i];
        char tok[5];
        size_t t = 0U;

        if (c == '\r')
        {
            tok[t++] = '\\';
            tok[t++] = 'r';
        }
        else if (c == '\n')
        {
            tok[t++] = '\\';
            tok[t++] = 'n';
        }
        else if ((c >= 0x20U) && (c < 0x7FU))
        {
            tok[t++] = (char) c;
        }
        else
        {
            tok[t++] = '<';
            tok[t++] = "0123456789abcdef"[c >> 4];
            tok[t++] = "0123456789abcdef"[c & 0xFU];
            tok[t++] = '>';
        }
        if ((o + t) >= (sizeof(line) - 1U))
        {
            line[o] = '\0';
            LOG_INFO("Spike", "%s %s", tag, line);
            vTaskDelay(pdMS_TO_TICKS(30));
            o = 0U;
        }
        for (size_t k = 0U; k < t; k++)
        {
            line[o++] = tok[k];
        }
    }
    line[o] = '\0';
    LOG_INFO("Spike", "%s %s", tag, line);
    vTaskDelay(pdMS_TO_TICKS(30));
}

/** Send @p len raw bytes (already framed), log verdict, elapsed time and the reply. */
static wifi_err_t spike_send(wifi_handle_t wifi, const char *label, const uint8_t *cmd, size_t len,
                             uint32_t timeout_ms)
{
    size_t got = 0U;
    const TickType_t t0 = xTaskGetTickCount();
    const wifi_err_t err = wifi_spike_raw_at(wifi, cmd, len, s_resp, sizeof(s_resp), &got, timeout_ms);
    const uint32_t ms = (uint32_t) ((xTaskGetTickCount() - t0) * 1000U / configTICK_RATE_HZ);

    LOG_INFO("Spike", "%s -> err=%d, %u bytes, %u ms", label, (int) err, (unsigned) got,
             (unsigned) ms);
    spike_log_text("  reply:", s_resp, got);
    return err;
}

/** Send a one-line command; the CR is appended here. */
static wifi_err_t spike_cmd(wifi_handle_t wifi, const char *label, const char *line,
                            uint32_t timeout_ms)
{
    const int n = snprintf((char *) s_cmd, sizeof(s_cmd), "%s\r", line);

    if ((n < 0) || ((size_t) n >= sizeof(s_cmd)))
    {
        return WIFI_ERR_INVALID_ARG;
    }
    return spike_send(wifi, label, s_cmd, (size_t) n, timeout_ms);
}

/** Send "<head>\r<data>" (PG, S3): the module reads @p len data bytes after the CR. */
static wifi_err_t spike_cmd_data(wifi_handle_t wifi, const char *label, const char *head,
                                 const uint8_t *data, size_t len, uint32_t timeout_ms)
{
    const int n = snprintf((char *) s_cmd, sizeof(s_cmd), "%s\r", head);

    if ((n < 0) || (((size_t) n + len) > sizeof(s_cmd)))
    {
        LOG_ERROR("Spike", "%s: does not fit the %u byte command buffer", label,
                  (unsigned) sizeof(s_cmd));
        return WIFI_ERR_INVALID_ARG;
    }
    (void) memcpy(&s_cmd[n], data, len);
    return spike_send(wifi, label, s_cmd, (size_t) n + len, timeout_ms);
}

/** Load one PEM into the module: PG=<set>,<type>,<len>. Type 0 = CA, 1 = certificate, 2 = key. */
static wifi_err_t spike_load_pem(wifi_handle_t wifi, const char *label, unsigned type,
                                 const char *pem, size_t pem_len)
{
    char head[40];

    (void) snprintf(head, sizeof(head), "PG=%u,%u,%u", (unsigned) SPIKE_CERT_SET, type,
                    (unsigned) pem_len);
    return spike_cmd_data(wifi, label, head, (const uint8_t *) pem, pem_len, 20000U);
}

/** Minimal MQTT 3.1.1 packets, enough to prove an application-level round trip. */
static size_t spike_mqtt_connect(uint8_t *out)
{
    static const char id[] = "wifi-tls-spike";
    const size_t id_len = sizeof(id) - 1U;
    size_t o = 0U;

    out[o++] = 0x10U;
    out[o++] = (uint8_t) (10U + 2U + id_len);
    out[o++] = 0x00U;
    out[o++] = 0x04U;
    out[o++] = 'M';
    out[o++] = 'Q';
    out[o++] = 'T';
    out[o++] = 'T';
    out[o++] = 0x04U;
    out[o++] = 0x02U;
    out[o++] = 0x00U;
    out[o++] = 0x3CU;
    out[o++] = 0x00U;
    out[o++] = (uint8_t) id_len;
    (void) memcpy(&out[o], id, id_len);
    return o + id_len;
}

static size_t spike_mqtt_publish(uint8_t *out)
{
    static const char topic[] = "spike/wifi-tls";
    static const char payload[] = "hello through the module's own TLS";
    const size_t tl = sizeof(topic) - 1U;
    const size_t pl = sizeof(payload) - 1U;
    size_t o = 0U;

    out[o++] = 0x30U; /* PUBLISH, QoS 0 */
    out[o++] = (uint8_t) (2U + tl + pl);
    out[o++] = 0x00U;
    out[o++] = (uint8_t) tl;
    (void) memcpy(&out[o], topic, tl);
    o += tl;
    (void) memcpy(&out[o], payload, pl);
    return o + pl;
}

